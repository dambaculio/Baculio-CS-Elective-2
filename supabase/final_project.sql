create table if not exists public.roles (
  id          bigint generated by default as identity primary key,
  role        varchar not null unique,
  created_at  timestamptz not null default now(),
  encoded_by  uuid references auth.users (id) on delete set null
);

create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  created_at  timestamptz not null default now(),
  email       text,
  firstname   text,
  lastname    text,
  role_id     bigint references public.roles (id)
);

create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null unique
);

create table if not exists public.products (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  name         text not null check (length(trim(name)) > 0),
  description  text,
  stock        smallint not null default 0 check (stock >= 0),
  image_url    text,
  category_id  bigint not null references public.categories (id) on delete restrict,
  price        real default 0 check (price >= 0)
);

create table if not exists public.orders (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  user_id     uuid references auth.users (id) on delete set null,
  status      text default 'pending'
              check (status in ('pending', 'done', 'shipped', 'delivered', 'cancelled')),
  total       numeric(12, 2) default 0 check (total >= 0)
);

create table if not exists public.order_items (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  order_id      bigint not null references public.orders (id) on delete cascade,
  product_id    bigint not null references public.products (id),
  unit_price    numeric(10, 2) not null check (unit_price >= 0),
  quantity      bigint not null check (quantity > 0)
);

create index if not exists products_price_idx       on public.products (price);
create index if not exists products_category_idx    on public.products (category_id);
create index if not exists orders_user_created_idx  on public.orders (user_id, created_at desc);
create index if not exists order_items_order_idx    on public.order_items (order_id);

