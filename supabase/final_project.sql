create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  full_name text := coalesce(
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'name'
  );
begin
  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    new.email,
    coalesce(
      new.raw_user_meta_data ->> 'firstname',
      new.raw_user_meta_data ->> 'given_name',
      split_part(full_name, ' ', 1)
    ),
    coalesce(
      new.raw_user_meta_data ->> 'lastname',
      new.raw_user_meta_data ->> 'family_name',
      case when position(' ' in full_name) > 0
           then substring(full_name from position(' ' in full_name) + 1)
      end
    ),
    (select id from public.roles where role = 'customer')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

insert into public.profiles (id, email, firstname, lastname, role_id)
select
  u.id,
  u.email,
  coalesce(u.raw_user_meta_data ->> 'firstname',
           split_part(coalesce(u.raw_user_meta_data ->> 'full_name',
                               u.raw_user_meta_data ->> 'name'), ' ', 1)),
  u.raw_user_meta_data ->> 'lastname',
  (select id from public.roles where role = 'customer')
from auth.users u
on conflict (id) do nothing;

create or replace function public.is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  return exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid() and r.role = 'admin'
  );
end;
$$;

